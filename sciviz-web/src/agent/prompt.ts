export function promptForSidebarTurn(contextJson: string, userText: string, historyFacts = ''): string {
  return `${SIDEBAR_SYSTEM_PROMPT}\n\n<当前项目上下文>\n${contextJson}\n</当前项目上下文>${historyFacts ? `\n\n<历史用户原话与工具事实>\n${historyFacts}\n</历史用户原话与工具事实>` : ''}\n\n<用户问题>\n${userText}\n</用户问题>`
}

